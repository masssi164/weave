#!/usr/bin/env python3
"""Select deterministic gates from complete input groups; ambiguity runs all gates."""
from __future__ import annotations

import argparse
import os
import re
import subprocess
from pathlib import Path, PurePosixPath

GATES = ('user', 'admin', 'client', 'admin_console', 'infra', 'docs', 'rust', 'backend')
# These roots have known owners. A new root must be reviewed before it can skip gates.
KNOWN_ROOTS = {
    '.github', '.specify', 'client', 'admin-console', 'contracts', 'docs', 'e2e',
    'fixtures', 'gradle', 'infra', 'release', 'rust', 'server', 'specs', 'tools',
    'weave-admin-api-client', 'weave-user-api-client', 'weave-application-core',
    'weave-files-core', 'weave-persistence-jpa', 'weave-mcp-server',
    'weave-product-e2e', 'weave-runtime-provider-adapters', 'weave-runtime-security-adapters',
}
KNOWN_FILES = {'AGENTS.md', 'CONTRIBUTING.md', 'LICENSE', 'NOTICE.md', 'README.md',
               'THIRD_PARTY_NOTICES.md', 'Makefile', 'Cargo.toml', 'Cargo.lock',
               'flutter_rust_bridge.yaml', '.gitignore', '.gitattributes', '.editorconfig'}


def select(paths: list[str] | None) -> dict[str, bool]:
    result = dict.fromkeys(GATES, False)
    # These static guards read cross-boundary source, mappings and documentation.
    # Their dependency closure is intentionally not path-pruned until enumerated.
    result['infra'] = result['docs'] = True
    if paths is None or not paths:
        return dict.fromkeys(GATES, True)
    for path in paths:
        parts = PurePosixPath(path).parts
        if (not parts or path.startswith('/') or '..' in parts
                or (parts[0] not in KNOWN_ROOTS and path not in KNOWN_FILES)
                or path.startswith(('gradle/', '.github/', '.specify/', 'tools/'))
                or path in {'build.gradle', 'settings.gradle', 'gradlew', 'gradlew.bat', 'Makefile'}):
            return dict.fromkeys(GATES, True)
        root = parts[0]
        # JVM Gradle source/resource/test inputs and native JNI dependencies do not
        # consume root documentation or Flutter files. Module-local docs remain
        # covered by their owning module root (for example server/docs).
        if root not in {'docs', 'client'} and path not in {'README.md', 'AGENTS.md', 'CONTRIBUTING.md'}:
            result['backend'] = True
        if root == 'contracts':
            if path == 'contracts/openapi/weave-user-openapi.json':
                result['user'] = result['client'] = result['admin_console'] = True
            elif path == 'contracts/openapi/weave-admin-openapi.json':
                result['admin'] = result['admin_console'] = True
            elif path != 'contracts/openapi/weave-openapi.json':
                result['user'] = result['admin'] = result['client'] = result['admin_console'] = True
        if root == 'client':
            result['client'] = True
            # Full client config/verification/toolchain is consumed by Dart generation.
            # Ordinary implementation changes are covered by the independent boundary gate.
            if not path.startswith(('client/lib/', 'client/test/', 'client/assets/')) or path.startswith('client/lib/generated/'):
                result['user'] = True
            result['docs'] = True  # screenshots are generated by clientCi
        if root == 'admin-console':
            result['admin_console'] = True
            if path.startswith('admin-console/src/generated/user-client/'):
                result['user'] = True
            elif path.startswith('admin-console/src/generated/admin-client/'):
                result['admin'] = True
            elif not path.startswith('admin-console/src/'):
                result['user'] = result['admin'] = True
        if root == 'weave-user-api-client':
            result['user'] = True
        if root == 'weave-admin-api-client':
            result['admin'] = True
        if root == 'infra':
            result['infra'] = True
        if root in {'docs', 'release', 'fixtures', 'specs', 'e2e'} or path in KNOWN_FILES:
            result['docs'] = True
        if root == 'rust' or path in {'Cargo.toml', 'Cargo.lock', 'flutter_rust_bridge.yaml'}:
            result['rust'] = result['client'] = result['user'] = True
    return result


def changed_paths(base: str, head: str = 'HEAD') -> list[str] | None:
    if not re.fullmatch(r'[0-9a-f]{40}', base) or base == '0' * 40:
        return None
    try:
        # --no-renames deliberately includes both old and new ownership on renames.
        diff = subprocess.run(['git', 'diff', '--name-only', '--no-renames', '-z', base, head],
                              check=True, capture_output=True).stdout
        return [entry.decode('utf-8') for entry in diff.split(b'\0') if entry]
    except (subprocess.CalledProcessError, UnicodeDecodeError):
        return None


def validate_results(impact: dict[str, str], results: dict[str, str]) -> None:
    for gate in GATES:
        selected = impact.get(gate)
        if selected not in {'true', 'false'}:
            raise ValueError(f'{gate}: missing or malformed impact output')
        expected = 'success' if selected == 'true' else 'skipped'
        if results.get(gate) != expected:
            raise ValueError(f'{gate}: expected {expected}, got {results.get(gate)!r}')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base', default='')
    parser.add_argument('--head', default='HEAD')
    args = parser.parse_args()
    result = select(changed_paths(args.base, args.head))
    output = '\n'.join(f'{key}={str(value).lower()}' for key, value in result.items()) + '\n'
    print(output, end='')
    if os.environ.get('GITHUB_OUTPUT'):
        with Path(os.environ['GITHUB_OUTPUT']).open('a') as stream:
            stream.write(output)


if __name__ == '__main__':
    main()
